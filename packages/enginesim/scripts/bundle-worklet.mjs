// Glue the Emscripten module and the processor into the one file addModule() can load.
//
// An AudioWorkletGlobalScope is a module scope. Two addModule() calls do not share bindings, so the
// processor cannot be handed `createEngineSim` by loading the glue separately — they have to be one
// script. This is that concatenation, and it is deliberately trivial: no bundler, no transform, no
// minifier standing between a stack trace and the line that threw.
//
//   node packages/enginesim/scripts/bundle-worklet.mjs
//
// build-wasm.mjs calls this at the end. Run it on its own after editing src/processor.js, which is
// much faster than a full toolchain rebuild.

import { readFileSync, writeFileSync, statSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import process from 'node:process'

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const gluePath = join(packageRoot, 'wasm', 'enginesim.js')
const processorPath = join(packageRoot, 'src', 'processor.js')
const outputPath = join(packageRoot, 'wasm', 'worklet.js')

let glue
try {
  glue = readFileSync(gluePath, 'utf8')
} catch {
  console.error(`No ${gluePath}. Run scripts/build-wasm.mjs first.`)
  process.exit(1)
}
const processor = readFileSync(processorPath, 'utf8')

// The glue ends with a CommonJS/AMD export tail guarded by `typeof exports`/`typeof define`. Both
// are undefined in a worklet so it is inert, and leaving it alone keeps this file byte-faithful to
// what Emscripten produced — the same bytes the Node probe requires.
const banner = `// GENERATED by packages/enginesim/scripts/bundle-worklet.mjs. Do not edit.
// = wasm/enginesim.js (Emscripten glue, generated from native/ + Open Engine Simulator)
// + src/processor.js  (the AudioWorkletProcessor)
// Edit those, then re-run the script.
`

writeFileSync(outputPath, `${banner}\n${glue}\n\n${processor}`)
console.log(`wasm/worklet.js  ${(statSync(outputPath).size / 1e6).toFixed(2)} MB`)
