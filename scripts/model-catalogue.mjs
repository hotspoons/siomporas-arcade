#!/usr/bin/env node
// Every .glb the arcade serves, as a list the viewer can bake in.
//
//   node scripts/model-catalogue.mjs [--check]
//
// `models.html` ships with a catalogue so it opens with something in it rather than an empty file
// picker. That catalogue has to match what is actually on disk — a bundled list that has drifted is
// worse than no list, because every stale entry is a 404 the viewer can only report after the user
// has clicked it. This regenerates the block in place, between the two markers in the HTML.
//
// Only `apps/arcade/public` is scanned. The viewer is served from there, so those are the paths
// that resolve at runtime; a model living under another app is not reachable from this page and has
// no business in the list. Anything else can still be loaded by path or dropped on the window.
//
// `apps/arcade/public/assets` is a MIRROR — gitignored, rebuilt from each game's own `public/` by
// scripts/sync-arcade-assets.mjs on every dev and build. So run that first, or this scans a stale
// tree and bakes paths that will not exist in CI:
//
//   node scripts/sync-arcade-assets.mjs && node scripts/model-catalogue.mjs
//
// A model belongs to a game, never to the arcade: put it in that game's public/ and let the mirror
// carry it across.
//
// --check exits non-zero if the file is out of date, for CI.

import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

// Resolved from this file, not from the working directory: npm runs it as apps/arcade's
// `predev`/`prebuild`, where the cwd is that package rather than the repository.
const REPO = fileURLToPath(new URL('..', import.meta.url));
const ROOT = join(REPO, 'apps/arcade/public');
const PAGE = join(REPO, 'apps/arcade/public/models.html');
const BEGIN = '// <<< CATALOGUE — generated by scripts/model-catalogue.mjs, do not edit by hand';
const END = '// >>> CATALOGUE';

// Group label per top-level asset directory. Anything unlisted falls back to its folder name, so a
// new directory shows up sensibly without needing an entry here.
const GROUPS = {
  'assets/crown/chars/kestrel': 'Fighter · reconstructed',
  'assets/props': 'Track props',
  'assets/nature': 'Nature',
  'assets/cars': 'Cars',
};

// The viewer opens on the first entry, so order is a choice about what it shows by default rather
// than a detail: the reconstructions are what this experiment exists to look at. Groups not named
// here sort after these, alphabetically.
const ORDER = ['Fighter · reconstructed', 'Track props', 'Cars', 'Nature'];
const rank = (g) => { const i = ORDER.indexOf(g); return i < 0 ? ORDER.length : i; };

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.name.endsWith('.glb')) out.push(full);
  }
  return out;
}

const rows = walk(ROOT)
  .map((full) => {
    const rel = relative(ROOT, full).split('\\').join('/');
    const dir = rel.split('/').slice(0, -1).join('/');
    const name = rel.split('/').pop().replace(/\.glb$/, '');
    return { path: '/' + rel, name, group: GROUPS[dir] ?? dir.split('/').pop(), kb: Math.round(statSync(full).size / 1024) };
  })
  .sort((a, b) => rank(a.group) - rank(b.group) || a.group.localeCompare(b.group) || a.name.localeCompare(b.name));

const body = rows.map((r) => `  ${JSON.stringify(r)},`).join('\n');
const block = `${BEGIN}\nconst CATALOGUE = [\n${body}\n];\n${END}`;

const html = readFileSync(PAGE, 'utf8');
const start = html.indexOf(BEGIN);
const stop = html.indexOf(END);
if (start < 0 || stop < 0) {
  console.error(`model-catalogue: markers not found in ${PAGE} — has the block been renamed?`);
  process.exit(2);
}
const next = html.slice(0, start) + block + html.slice(stop + END.length);

if (process.argv.includes('--check')) {
  if (next !== html) {
    console.error(`model-catalogue: ${PAGE} is out of date — run: node scripts/model-catalogue.mjs`);
    process.exit(1);
  }
  console.log(`model-catalogue: up to date, ${rows.length} models`);
} else {
  writeFileSync(PAGE, next);
  const groups = [...new Set(rows.map((r) => r.group))];
  console.log(`${PAGE}  ${rows.length} models in ${groups.length} groups`);
  for (const g of groups) console.log(`  ${g}: ${rows.filter((r) => r.group === g).length}`);
}
