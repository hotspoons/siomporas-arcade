#!/usr/bin/env node
// The arcade serves three games from one origin, so it has to serve their static files too — the
// car models Turbo Radrun bakes its sprites from, and each game's bundled typefaces. Rather than
// keep a second copy of any of it in the repository, this mirrors each game's `public/` into the
// arcade's before dev and before build (npm's `predev`/`prebuild` run it), and the mirrored
// directories are gitignored. A game stays the owner of its own assets.
//
// Two files collide because every game has one: `favicon.svg`, which the arcade replaces with its
// own, and `fonts/fonts.css`, which is concatenated instead — all three games' faces are wanted at
// once, since the lobby shows all three games' typography before any of them is mounted.

import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

// npm runs this as apps/arcade's `predev`/`prebuild`, so the working directory is that package and
// not the repository. Everything below is resolved from the repository root instead.
const ROOT = fileURLToPath(new URL('..', import.meta.url))
const at = (...parts) => path.join(ROOT, ...parts)

/** Recursive copy, one file at a time. `fs.cpSync`'s native directory walk is blocked in the dev container. */
function copyTree(src, dest, skip = () => false, wrote = null) {
  mkdirSync(dest, { recursive: true })
  for (const entry of readdirSync(src, { withFileTypes: true })) {
    if (skip(entry.name)) continue
    const from = path.join(src, entry.name)
    const to = path.join(dest, entry.name)
    if (entry.isDirectory()) copyTree(from, to, skip, wrote)
    else {
      copyFileSync(from, to)
      wrote?.add(to)
    }
  }
}

/** Every file under a directory, so what the mirror did not write can be found and removed. */
function walk(dir, out = []) {
  if (!existsSync(dir)) return out
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(p, out)
    else out.push(p)
  }
  return out
}

const GAMES = ['coast', 'stuntin', 'conduit', 'fighter']
const ARCADE = at('apps/arcade/public')
/** Handled specially below, never copied. */
const SKIP = new Set(['favicon.svg', 'fonts'])

let copied = 0
// A MIRROR, NOT AN ACCUMULATION. Copying over the top leaves anything a game has since deleted
// sitting in the arcade's copy for ever, and it ships. The sprite atlas is content-hashed, so every
// re-bake used to leave its predecessor behind — eleven megabytes of sheet nothing can ever ask for,
// and another eleven on the next bake. Track what the mirror writes and remove whatever it did not.
const mirrored = new Set()

for (const game of GAMES) {
  const from = at('apps', game, 'public')
  if (!existsSync(from)) continue
  for (const entry of ['assets']) {
    const src = path.join(from, entry)
    if (!existsSync(src) || SKIP.has(entry)) continue
    copyTree(src, path.join(ARCADE, entry), () => false, mirrored)
    copied++
  }
}

let pruned = 0
for (const file of walk(path.join(ARCADE, 'assets'))) {
  if (mirrored.has(file)) continue
  rmSync(file, { force: true })
  pruned++
}

// Fonts: one directory holding every game's faces, and one stylesheet declaring all of them.
const fontsOut = path.join(ARCADE, 'fonts')
rmSync(fontsOut, { recursive: true, force: true })
mkdirSync(fontsOut, { recursive: true })

const css = ['/* Generated by scripts/sync-arcade-assets.mjs — every game\'s faces, in one sheet. */']
const licenses = ['Fonts bundled with the arcade. Each game\'s own LICENSES.txt, concatenated.\n']

for (const game of GAMES) {
  const from = at('apps', game, 'public', 'fonts')
  if (!existsSync(from)) continue
  copyTree(from, fontsOut, (name) => name === 'fonts.css' || name === 'LICENSES.txt')
  const sheet = path.join(from, 'fonts.css')
  if (existsSync(sheet)) {
    css.push(`\n/* --- ${game} --- */`)
    // Drop each sheet's own header comment; one banner at the top is enough.
    css.push(readFileSync(sheet, 'utf8').replace(/^\/\*[\s\S]*?\*\/\n?/, '').trimEnd())
  }
  const lic = path.join(from, 'LICENSES.txt')
  if (existsSync(lic)) licenses.push(`\n=== ${game} ===\n`, readFileSync(lic, 'utf8'))
}

writeFileSync(path.join(fontsOut, 'fonts.css'), css.join('\n') + '\n')
writeFileSync(path.join(fontsOut, 'LICENSES.txt'), licenses.join(''))

console.log(`arcade assets: ${copied} directories mirrored${pruned ? `, ${pruned} stale files removed` : ''}, fonts merged from ${GAMES.length} games`)
